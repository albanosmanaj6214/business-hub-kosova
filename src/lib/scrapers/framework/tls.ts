// Keep this list tiny and explicit. Only hosts we have verified serve a valid leaf
// with a missing PUBLIC intermediate belong here.
export const INCOMPLETE_CHAIN_HOSTS = new Set<string>(['www.atk-ks.org', 'atk-ks.org'])

export function needsChainRepair(url: string): boolean {
  try {
    return INCOMPLETE_CHAIN_HOSTS.has(new URL(url).hostname)
  } catch {
    return false
  }
}

/** System roots + the supplied public intermediate(s). Verification stays on. */
export function caBundleWithIntermediates(): string[] {
  return [...rootCertificates, GODADDY_G2_INTERMEDIATE]
}
